import assert from 'node:assert/strict';
import {createOriginalCommission,evaluateNewGeometry,ARTIFACT_SCHEMA,COMMISSION_SCHEMA,SLOTS,NO_GO_PROTOTYPES} from './skin11-original-factory-core.mjs';
const requests=[
 'Quiero armadura de dragon roja, escamas esculpidas y cabeza proporcionada',
 'Quiero guerrero samurai de metal negro con casco kabuto nuevo',
 'Armadura de rey oscuro con corona integrada y hombreras ajustadas',
 'Armadura celestial blanca y dorada con alas pequeñas articuladas',
 'Armadura futurista de titanio azul con visor curvo',
 'Guardián del bosque verde con plumas y láminas de madera',
 'Armadura de hielo con cristal empotrado y articulaciones',
 'Paladín de tormenta con relámpagos integrados en el metal',
 'Guerrero bárbaro con correas, acero y armadura ligera',
 'Armadura demoníaca con cuernos cortos y grebas articuladas'
];
for(const prompt of requests){
 const c=createOriginalCommission({prompt});
 assert.equal(c.schema,COMMISSION_SCHEMA);
 assert.equal(c.mode,'text');
 assert.equal(c.input.aiInterpretation.status,'NOT_CONNECTED');
 assert.equal(c.autoGenerated3D,false);
 assert.equal(c.uniqueness.sourceMeshDeformForbidden,true);
 assert.equal(c.uniqueness.oldSkin3ReadOnly,true);
 assert.deepEqual(Object.keys(c.design.requiredSlots),SLOTS);
 assert(Object.values(c.design.requiredSlots).every(s=>s.originalMeshCopied===false && s.sourceTrianglesReused===0));
 assert.equal(c.gate.premiumApproved,false);
 assert.deepEqual(evaluateNewGeometry(c,null).errors,['NEW_GLTF_NOT_PROVIDED','HUMAN_ART_APPROVAL_PENDING']);
}
const reference={mime:'image/png',width:1024,height:1024,sha256:'a'.repeat(64),dominantColors:['#885533','#eeeeee']};
const img=createOriginalCommission({reference});
assert.equal(img.mode,'image');assert.equal(img.input.image.imageSemanticsAnalyzed,false);
const both=createOriginalCommission({reference,prompt:requests[0]});
assert.equal(both.mode,'text+image');
assert.notEqual(both.id,img.id);
assert.throws(()=>createOriginalCommission({prompt:'rojito'}));
assert.throws(()=>createOriginalCommission({prompt:requests[0],reference:{...reference,sha256:'wrong'}}));
assert.throws(()=>createOriginalCommission({prompt:requests[0],reference:{...reference,mime:'text/html'}}));
const c=createOriginalCommission({prompt:requests[2]});
const good={schema:ARTIFACT_SCHEMA,commissionId:c.id,creationMode:'AUTHOR_FRESH_TOPOLOGY',sourceMeshDeformed:false,
 sourceTrianglesCopied:0,sourceVerticesCopied:0,armorSlots:12,rigBoneCount:23,animationClips:22,
 maleFemaleScreenshots:true,frontSideBackScreenshots:true,anatomyFitMeasured:true,floatingComponents:false,severeClipFrames:0};
const hold=evaluateNewGeometry(c,good);
assert.equal(hold.status,'NO_GO');assert.equal(hold.technicalPass,true);
assert.equal(evaluateNewGeometry(c,good,{artistApproval:true}).gameDeployAllowed,false);
assert.equal(evaluateNewGeometry(c,{...good,sourceTrianglesCopied:1},{artistApproval:true}).status,'NO_GO');
assert(evaluateNewGeometry(c,{...good,creationMode:'DEFORM_LEGACY'},{artistApproval:true}).errors.includes('NOT_FRESH_TOPOLOGY'));
assert(evaluateNewGeometry(c,{...good,legacyPrototypeId:NO_GO_PROTOTYPES[0]},{artistApproval:true}).errors.includes('REJECTED_ART_PROTOTYPE'));
assert(evaluateNewGeometry(c,{...good,rigBoneCount:22},{artistApproval:true}).errors.includes('CLAUDECRAFT_RIG_AND_22_CLIPS_REQUIRED'));
console.log('HIGHFLY_SKIN11_ORIGINAL_ARMOR_FACTORY_TEN_TEXT_AND_IMAGE_SCHEMAS_NO_LEGACY_DEFORMATION_HARD_GATE_GREEN=1');
