async function imageMetadata(file){
 if(!file)return null;
 if(!['image/png','image/jpeg','image/webp'].includes(file.type)||file.size>12*1024*1024)
  throw Error('Imagen inválida: JPG/PNG/WebP de hasta 12 MB');
 const bytes=await file.arrayBuffer();
 const hash=[...new Uint8Array(await crypto.subtle.digest('SHA-256',bytes))].map(x=>x.toString(16).padStart(2,'0')).join('');
 const b=await createImageBitmap(file);const w=b.width,h=b.height;
 if(w<32||h<32||w>8192||h>8192){b.close();throw Error('Imagen fuera de límites de 32 a 8192 píxeles')}
 const c=document.createElement('canvas');c.width=48;c.height=48;const ctx=c.getContext('2d',{willReadFrequently:true});
 ctx.drawImage(b,0,0,48,48);b.close();
 const a=ctx.getImageData(0,0,48,48).data,m=new Map();
 for(let i=0;i<a.length;i+=16){
  if(a[i+3]<60)continue;
  const color='#'+[0,1,2].map(k=>Math.min(255,Math.floor(a[i+k]/32)*32+16).toString(16).padStart(2,'0')).join('');
  m.set(color,(m.get(color)||0)+1);
 }
 return {mime:file.type,width:w,height:h,sha256:hash,dominantColors:[...m].sort((x,y)=>y[1]-x[1]).slice(0,5).map(x=>x[0])};
}
