import {createOriginalCommission} from './skin11-original-factory-core.mjs';
const $=id=>document.getElementById(id);
const KEY='highfly.skin11.original.commissions.v1';
let current=null, reference=null, imageUrl=null;
let history=[];
function status(t){$('status').textContent=t}
function latest(){return current}
function snapshot(){return {schema:current?.schema||null,id:current?.id||null,mode:current?.mode||null,
 historyCount:history.length,autoGenerated3D:current?.autoGenerated3D??false,
aiStatus:current?.input.aiInterpretation.status||'NOT_CONNECTED',legacyGeometryForbidden:current?.uniqueness.sourceMeshDeformForbidden??true,
referencePresent:!!reference}}
function drawHistory(){
 $('history').replaceChildren();
 if(!history.length){$('history').textContent='Sin encargos.';return}
 for(const item of history){
  const b=document.createElement('button');
  b.textContent=item.id+' · '+item.mode+' · '+item.input.prompt.slice(0,75);
  b.onclick=()=>{current=item;showCurrent();status('Encargo recuperado. La foto original no se guarda; se conserva SHA-256 y paleta.')};
  $('history').append(b);
 }
}
function loadHistory(){
 try{
  const x=JSON.parse(localStorage.getItem(KEY)||'[]');
  history=Array.isArray(x)?x.filter(z=>z.schema==='highfly.skin11.original-armor-commission/1').slice(0,20):[];
 }catch{history=[];status('Almacenamiento local desactivado. Podés exportar el encargo.')}
 drawHistory();
}
function store(item){
 history=[item,...history.filter(x=>x.id!==item.id)].slice(0,20);
 try{localStorage.setItem(KEY,JSON.stringify(history))}catch{status('Sin almacenamiento local: exportá el JSON')}
 drawHistory();
}
function showCurrent(){
 if(!current)return;
 $('result').textContent=[
  'Encargo: '+current.id+' · Modo '+current.mode,
  'Estilos detectados: '+current.design.tags.join(', '),
  'Piezas originales por construir: '+Object.keys(current.design.requiredSlots).length,
  'ClaudeCraft permitido: medidas / Rig_Medium / weights / 22 animaciones',
  'Se prohíbe: copiar, deformar o recolorear las armaduras anteriores',
  'Lectura de geometría de foto por IA: '+current.input.imageGeometryExtraction,
  'Motor IA: '+current.input.aiInterpretation.status,
  'Generación GLB: '+(current.autoGenerated3D?'GENERADO':'PENDIENTE · necesita modelado original'),
  'Aprobación artística: PENDIENTE · No integra HIGHFLY'
 ].join('\n');
 $('export').disabled=false;
}
async function imageMetadata(file){
 if(!file)return null;
 if(!['image/png','image/jpeg','image/webp'].includes(file.type)||file.size>12*1024*1024)
  throw Error('Imagen inválida: JPG/PNG/WebP de hasta 12 MB');
 const bytes=await file.arrayBuffer();
 const sha=await crypto.subtle.digest('SHA-256',bytes);
 const hash=[...new Uint8Array(sha)].map(x=>x.toString(16).padStart(2,'0')).join('');
 const bitmap=await createImageBitmap(file);
 const w=bitmap.width,h=bitmap.height;
 if(w<32||h<32||w>8192||h>8192)throw Error('Resolución fuera de 32–8192 px');
 const c=document.createElement('canvas');c.width=48;c.height=48;
 const ctx=c.getContext('2d',{willReadFrequently:true});ctx.drawImage(bitmap,0,0,48,48);
 bitmap.close();
 const data=ctx.getImageData(0,0,48,48).data;
 const colors=new Map();
 for(let i=0;i<data.length;i+=16){
  if(data[i+3]<60)continue;
  const v=[0,1,2].map(k=>Math.min(255,Math.floor(data[i+k]/32)*32+16).toString(16).padStart(2,'0')).join('');
  colors.set('#'+v,(colors.get('#'+v)||0)+1);
 }
 const dominantColors=[...colors].sort((a,b)=>b[1]-a[1]).slice(0,5).map(x=>x[0]);
 return {mime:file.type,width:w,height:h,sha256:hash,dominantColors};
}
$('image').addEventListener('change',async()=>{
 const file=$('image').files?.[0];
 try{
  if(imageUrl)URL.revokeObjectURL(imageUrl);imageUrl=null;reference=null;
  $('preview').style.display='none';
  if(!file){status('Referencia quitada. Podés seguir solamente con texto.');return}
  reference=await imageMetadata(file);
  imageUrl=URL.createObjectURL(file);$('preview').src=imageUrl;$('preview').style.display='block';
  status('Imagen cargada LOCALMENTE · '+reference.width+'×'+reference.height+
    ' · SHA-256 listo. Sin IA remota ni subida al servidor.');
 }catch(e){reference=null;status('❌ '+e.message)}
});
$('build').onclick=()=>{
 try{
  current=createOriginalCommission({prompt:$('prompt').value,reference});
  store(current);showCurrent();
  status('✅ Encargo original estructurado. FALTA generar geometría nueva con IA/Blender y pasar QA.');
 }catch(e){status('❌ '+e.message)}
};
$('export').onclick=()=>{
 if(!current)return;
 const blob=new Blob([JSON.stringify(current,null,2)],{type:'application/json'});
 const url=URL.createObjectURL(blob);
 const a=document.createElement('a');a.href=url;a.download=current.id+'-ORIGINAL-SKIN.json';a.click();
 setTimeout(()=>URL.revokeObjectURL(url),1000);
 status('✅ Contrato JSON exportado, listo para iniciar modelado original; NO es un GLB generado.');
};
loadHistory();
window.__HF_SKIN11_FACTORY__=Object.freeze({snapshot,latest});
